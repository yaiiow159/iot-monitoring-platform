package com.iotmon.domain.cabinet;

/**
 * 機櫃類型。決定這個櫃子能容納哪些機型，以及整櫃層級要套用哪些告警。
 *
 * <p>做成列舉而不是自由文字，是因為「哪些機型可以裝進哪種櫃子」這條規則
 * 需要一組有限且已知的類型才能表達。真實世界的櫃子種類不會頻繁增加，
 * 增加時多一個列舉值也比多一筆設定資料安全——編譯器會提醒所有 switch 補上分支。
 */
public enum CabinetType {

    /** 配電櫃：電力模組與機櫃控制器 */
    POWER,

    /** 伺服器櫃：機櫃控制器與環境感測器 */
    SERVER,

    /** 感測櫃：只放環境感測器 */
    SENSOR
}
